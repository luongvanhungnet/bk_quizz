"use strict";
const assert = require("node:assert/strict");
const {actionForKey,navigationPlan}=require("./keyboard.js");
const ready={busy:false,editing:false,dirty:false,current:{id:"r1"},sourceReady:true,reviewer:"Human"};
const event=key=>({key,target:{tagName:"BODY"}});
assert.equal(actionForKey(event("ArrowUp"),ready),"approve");
assert.equal(actionForKey(event("ArrowDown"),ready),"reject");
assert.equal(actionForKey(event("ArrowLeft"),ready),"previous");
assert.equal(actionForKey(event("ArrowRight"),ready),"next");
for(const field of ["busy","editing","dirty"])assert.equal(actionForKey(event("ArrowUp"),{...ready,[field]:true}),null);
assert.equal(actionForKey({...event("ArrowUp"),repeat:true},ready),null);
assert.equal(actionForKey({...event("ArrowUp"),isComposing:true},ready),null);
for(const tagName of ["INPUT","TEXTAREA","SELECT"])assert.equal(actionForKey({...event("ArrowDown"),target:{tagName}},ready),null);
assert.equal(actionForKey({...event("ArrowDown"),target:{tagName:"DIV",isContentEditable:true}},ready),null);
assert.equal(actionForKey(event("ArrowUp"),{...ready,reviewer:""}),null);
assert.equal(actionForKey(event("ArrowUp"),{...ready,sourceReady:false}),null);
assert.equal(actionForKey(event("ArrowUp"),{...ready,current:null}),null);
assert.deepEqual(navigationPlan(99,100,0,205,1,100),{offset:100,index:0});
assert.deepEqual(navigationPlan(0,100,100,205,-1,100),{offset:0,index:99});
assert.deepEqual(navigationPlan(99,100,100,205,1,100),{offset:200,index:0});
assert.equal(navigationPlan(4,5,200,205,1,100),null);
assert.equal(navigationPlan(0,100,0,205,-1,100),null);
assert.deepEqual(navigationPlan(1,6,0,6,-1,100),{offset:0,index:0});
console.log("Keyboard guards and cross-page navigation PASS");
